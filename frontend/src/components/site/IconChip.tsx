/** 素のラインアイコン（チップ地なし）。ボタン内・テキスト横のインライン用。色は currentColor。 */
export function Icon({
  name,
  size = 16,
  strokeWidth = 2,
  className = "",
  label,
}: {
  name: IconName;
  size?: number;
  strokeWidth?: number;
  className?: string;
  label?: string;
}) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
    >
      {PATHS[name]}
    </svg>
  );
}

/**
 * 単色地＋白ラインアイコンのチップ（docs/55 §5-5 → docs/61 §3-5 で単色化）。
 * UIのアクセントは brand-600 の1系統だけ。グラデ地は廃止。
 * 絵文字はチャット吹き出しの会話文のみ残す（docs/61 §3-5）。
 */
export function IconChip({
  icon,
  size = 48,
  className = "",
  label,
}: {
  icon: IconName;
  size?: number;
  className?: string;
  label?: string;
}) {
  return (
    <span
      className={`inline-flex shrink-0 items-center justify-center rounded-2xl bg-brand-600 text-white shadow-soft ${className}`}
      style={{ width: size, height: size }}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
    >
      <svg
        width={Math.round(size * 0.52)}
        height={Math.round(size * 0.52)}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={2}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden
      >
        {PATHS[icon]}
      </svg>
    </span>
  );
}
