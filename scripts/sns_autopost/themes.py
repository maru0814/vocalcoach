# 投稿の柱（曜日 → 関数キー）。週次で回す。
PILLARS = [
    "diagnosis",  # 月: 声タイプ診断の誘導
    "tip",        # 火: 発声Tips
    "type",       # 水: 声タイプ紹介（1種）
    "tip",        # 木: 発声Tips
    "diagnosis",  # 金: 声タイプ診断の誘導
    "type",       # 土: 声タイプ紹介（1種）
    "tip",        # 日: 発声Tips
]


def template_post(pillar: str, day_index: int, app_url: str) -> str:
    """Geminiを使わない場合のフォールバック投稿文。"""
    if pillar == "diagnosis":
        return (
            "🎤 あなたの声って、どんなタイプ？\n"
            "15秒くらい歌うだけで、AIが8つの声タイプから診断します（無料）。\n"
            "似た声質のアーティストつき。結果はそのままシェアできます😊\n"
            f"{app_url}/voice-type\n"
            "#声診断 #ボイトレ #歌うま"
        )
    if pillar == "type":
        name, emoji, desc = VOICE_TYPES[day_index % len(VOICE_TYPES)]
        return (
            f"【声タイプ図鑑】{name} {emoji}\n"
            f"{desc}。\n"
            "あなたはどのタイプ？無料で診断できます👇\n"
            f"{app_url}/voice-type\n"
            "#声診断 #ボイトレ"
        )
    # tip
    tip = TIPS[day_index % len(TIPS)]
    return (
        f"🎵 今日の発声メモ\n{tip}\n\n"
        "録音を送ると、AIが発声を解析して直すところを教えます（無料）。\n"
        f"{app_url}\n"
        "#ボイトレ #歌の練習"
    )


def gemini_prompt(pillar: str, day_index: int, app_url: str) -> str:
    """Geminiに渡す生成指示。テンプレを下敷きに、自然な投稿文へリライトさせる。"""
    base = template_post(pillar, day_index, app_url)
    return (
        "あなたはAIボイストレーナー『ソラ先生』のSNS担当です。X(旧Twitter)に投稿する日本語ツイートを1つ書いてください。\n"
        "条件:\n"
        "- 140字以内（URLは23字換算で含めて調整）。\n"
        "- やさしく、専門用語は噛み砕く。絶対に効果を誇張しない（『プロになれる』等はNG）。\n"
        "- 末尾にURLとハッシュタグ2〜3個。\n"
        "- 絵文字は1〜3個まで。\n"
        f"- 必ずこのURLを入れる: {app_url}{'/voice-type' if pillar in ('diagnosis','type') else ''}\n"
        "下敷き（この内容・URLを保ちつつ、より自然で人を惹きつける文に）:\n"
        f"{base}\n"
        "出力はツイート本文のみ。前置きや説明は書かない。"
    )
