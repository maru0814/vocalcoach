def pillar_for(weekday: int, slot: int) -> str:
    """曜日(0=月)とスロット(1=昼/2=夜)から投稿の型を返す。"""
    table = PILLARS_2ND if slot == 2 else PILLARS
    return table[weekday % 7]


def _diagnose_link(app_url: str) -> str:
    return f"{app_url}/voice-type"


def template_post(pillar: str, day_index: int, app_url: str) -> dict:
    """Geminiを使わない場合のフォールバック本文。{text, link} を返す（link は自己リプ用）。"""
    if pillar == "self_type":
        types = " / ".join(f"{e}{n}" for n, e, _ in VOICE_TYPES)
        return {"text": ("あなたの歌声、実はこの8タイプのどれかです。\n\n"
                         f"{types}\n\n直感でどれっぽい？（プロフィールから無料で診断できます🎤）"),
                "link": _diagnose_link(app_url)}
    if pillar == "voice_type":
        n, e, d = VOICE_TYPES[day_index % len(VOICE_TYPES)]
        return {"text": (f"【声タイプ図鑑】{n} {e}\n{d}。\n\n"
                         "あなたは何タイプ？プロフィールのリンクから診断できます🎤"),
                "link": _diagnose_link(app_url)}
    if pillar == "contrarian":
        hook, body = CONTRARIAN[day_index % len(CONTRARIAN)]
        return {"text": f"{hook}\n\n{body}", "link": app_url}
    if pillar == "visual":
        return {"text": ("あなたの声は、どのタイプ？🎤\n\n"
                         "15秒歌うだけで、AIが8タイプ＋似た声質の歌手まで診断。\n"
                         "結果はそのままシェアできます。\n\n（プロフィールのリンクから無料で🎤）"),
                "link": _diagnose_link(app_url)}
    # tip（既定）: 高音・ミックス中心の実践Tips（長文・保存狙い）
    tip = TIPS[day_index % len(TIPS)]
    return {"text": f"🎤 今日のボイトレメモ\n\n{tip}", "link": app_url}


def gemini_prompt(pillar: str, day_index: int, app_url: str) -> str:
    """Geminiに渡す生成指示。下敷きの主旨・情報量を保ったまま自然にリライト。"""
    base = template_post(pillar, day_index, app_url)["text"]

    common = (
        "あなたはAIボイストレーナー『ソラ先生』のSNS担当（人間味のある“中の人”）です。"
        "X(旧Twitter)に投稿する日本語ポストを1つ書いてください。\n"
        "共通ルール:\n"
        "- 1行目で必ず読み手を止めるフック（誰の悩みか＋結論を一言）。\n"
        "- 改行と番号で“スキャンしやすく”。読み手が保存したくなる実用度を最優先。\n"
        "- 効果を誇張しない（『プロになれる』『誰でも一瞬で』等NG）。\n"
        "- **本文にURL・リンクは絶対に入れない**（誘導はプロフィール固定。reach減＆課金回避）。\n"
        "- **『リプで教えて』『コメントで』等のエンゲージ稼ぎの呼びかけは禁止**。\n"
        "- ハッシュタグは付けても2個まで。絵文字は1〜3個。馴れ馴れしすぎない。\n"
    )

    if pillar == "tip":
        style = (
            "今回は【実践Tips】。高音・ミックスボイス・換声点など“今日試せる具体的なやり方”を、"
            "踏み込んで書きます。短い一言で終わらせない。\n"
            "構成: ①強いフック（誰の何の悩みか＋結論）→ ②具体的な手順を番号付きで2〜3個→ "
            "③最後に一言の注意点 or 励まし。\n"
            "長さの目安: 全角200〜350字（X Premium想定の長文でOK。薄い内容で水増ししない）。\n"
            "専門用語（換声点・共鳴など）は一言で噛み砕く。\n"
        )
    elif pillar == "contrarian":
        style = (
            "今回は【逆張り】。よくある誤解を1行で否定→なぜ違うかを根拠つきで解説。\n"
            "煽りすぎず、読み終わって“なるほど”と専門性が伝わる長さ（全角150〜300字）。\n"
        )
    else:  # self_type / voice_type / visual = 診断導線
        style = (
            "今回は【声タイプ診断への導線】。声の個性を肯定し、“自分のタイプを知りたい”と"
            "思わせる。簡潔でテンポよく（全角80〜140字）。プロフィールのリンクから無料診断できることを自然に添える。\n"
        )

    return (
        common + style +
        "下敷き（この主旨・情報量・トーンを保ち、より自然で人を惹きつける文に）:\n"
        f"{base}\n"
        "出力はポスト本文のみ。前置き・説明・URL・ハッシュタグの羅列は不要。"
    )
