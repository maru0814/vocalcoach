def pillar_for(weekday: int, slot: int) -> str:
    """曜日(0=月)とスロット(1=昼/2=夜/3=朝)から投稿の型を返す。"""
    table = {2: PILLARS_2ND, 3: PILLARS_3RD}.get(slot, PILLARS)
    return table[weekday % 7]


def _diagnose_link(app_url: str) -> str:
    return f"{app_url}/voice-type"


# 2部構成の本投稿末尾に付ける“続きはリプ”案内。読者にリプを促すのではなく、
# 「自分の自己返信に本体（手順）を置いた」という案内（main方針のリプ乞い禁止と両立）。
NUDGE = "\n\n👇 具体的な手順（大事なとこ）はリプに置きました。"

# アーティスト発声解説の“続きはリプ”案内（推定であることを入口から明示）。
ARTIST_NUDGE = "\n\n👇 歌声の分解（音源からの推定）はリプに置きました。"


def _type_label(type_id: str) -> str:
    """声タイプid('rock'等) → 表示ラベル('【Rock🔥】')。"""
    for n, e, _ in VOICE_TYPES:
        if n.lower() == type_id.lower():
            return f"【{n}{e}】"
    return ""


def artist_bridge(type_id: str) -> str:
    """アーティスト発声解説の body 末尾に付ける診断ブリッジ（この型の導線の核）。"""
    return (f"\n\nこの声質、ソラの8タイプ診断だと{_type_label(type_id)}系。\n"
            "あなたの声がどのタイプかは、15秒歌えばAIが当てます（プロフィールから無料）。")


def template_post(pillar: str, day_index: int, app_url: str) -> dict:
    """Geminiを使わない場合のフォールバック。{text, reply, link} を返す。
    text=本投稿 / reply=自己返信に置く“本体” or None（短文の診断導線型は単発）/ link=リプ用URL。"""
    # アーティスト発声解説（docs/84）= 実名フック＋発声分解リプ＋診断ブリッジの2部構成。
    if pillar == "artist_analysis":
        e = ARTIST_ANALYSIS[day_index % len(ARTIST_ANALYSIS)]
        return {"text": e["hook"] + ARTIST_NUDGE,
                "reply": e["body"] + artist_bridge(e["type"]),
                "link": _diagnose_link(app_url)}
    # 診断導線（self_type / voice_type / visual）= “似てる歌手の正体当て”フック＋8タイプ早見リプの2部構成。
    # ラベル陳列（旧「【声タイプ図鑑】◯◯」）はやめ、好奇心ギャップで止めて診断に送る。
    if pillar == "self_type":
        return {"text": ("あなたの声、歌手なら誰に似てる？🎤\n\n"
                         f"たとえば {artists_for('rock')}、{artists_for('dramatic')}…\n"
                         "自分の声が“誰系”かは、意外と自分ではわからないもの。\n"
                         "15秒歌うだけで、AIが「似てる歌手」と声タイプを当てます。\n\n"
                         "👇 8タイプ（近い歌手の例つき）はリプに置きました。"),
                "reply": cheatsheet_reply(), "link": _diagnose_link(app_url)}
    if pillar == "voice_type":
        n, e, d = VOICE_TYPES[day_index % len(VOICE_TYPES)]
        return {"text": (f"{artists_for(n, 3)} みたいな声、憧れませんか？🎤\n\n"
                         f"この“{d}”は、診断だと【{n}{e}】タイプ。\n"
                         "あなたの声は8つのうちどれ？ AIが似てる歌手まで当てます。\n\n"
                         "👇 全8タイプ（近い歌手の例つき）はリプに置きました。"),
                "reply": cheatsheet_reply(), "link": _diagnose_link(app_url)}
    if pillar == "visual":
        return {"text": ("あなたの声は、どのタイプ？🎤\n\n"
                         f"{artists_for('mysterious')}系？ {artists_for('crystal')}系？\n"
                         "15秒歌うだけで、AIが8つの声タイプと「似てる歌手」を診断。\n\n"
                         "👇 8タイプ（近い歌手の例つき）はリプに。結果はそのままシェアOK。"),
                "reply": cheatsheet_reply(), "link": _diagnose_link(app_url)}
    if pillar == "contrarian":
        # 本投稿=誤解を1行で否定して止める / リプ本体=なぜ違うかの根拠解説
        hook, body = CONTRARIAN[day_index % len(CONTRARIAN)]
        return {"text": hook + NUDGE, "reply": body, "link": app_url}
    # tip（既定）: 本投稿=悩みフックで止める / リプ本体=番号付きの実践手順（保存狙い）
    tip = TIPS[day_index % len(TIPS)]
    hook_seed = tip.split("\n", 1)[0].rstrip("。") + "。"
    return {"text": hook_seed + NUDGE,
            "reply": f"🎤 今日のボイトレメモ\n\n{tip}", "link": app_url}


def gemini_prompt(pillar: str, day_index: int, app_url: str) -> str:
    """Geminiに渡す生成指示。下敷きの主旨・情報量を保ったまま自然にリライト。"""
    base = template_post(pillar, day_index, app_url)["text"]

    common = (
        "あなたはAIボイストレーナー『ソラ先生』のSNS担当（人間味のある“中の人”）です。"
        "X(旧Twitter)に投稿する日本語ポストを1つ書いてください。\n"
        "共通ルール:\n"
        "- 1行目で必ず読み手を止めるフック（誰の悩みか＋結論を一言）。\n"
        "- 改行と番号で“スキャンしやすく”。読み手が保存したくなる実用度を最優先。\n"
        "- 効果を誇張しない（『プロになれる』『誰でも一瞬で』等NG）。\n"
        "- **本文にURL・リンクは絶対に入れない**（誘導はプロフィール固定。reach減＆課金回避）。\n"
        "- **『リプで教えて』『コメントで』等のエンゲージ稼ぎの呼びかけは禁止**。\n"
        "- ハッシュタグは付けても2個まで。絵文字は1〜3個。馴れ馴れしすぎない。\n"
    )

    if pillar == "tip":
        style = (
            "今回は【実践Tips】。高音・ミックスボイス・換声点など“今日試せる具体的なやり方”を、"
            "踏み込んで書きます。短い一言で終わらせない。\n"
            "構成: ①強いフック（誰の何の悩みか＋結論）→ ②具体的な手順を番号付きで2〜3個→ "
            "③最後に一言の注意点 or 励まし。\n"
            "長さの目安: 全角200〜350字（X Premium想定の長文でOK。薄い内容で水増ししない）。\n"
            "専門用語（換声点・共鳴など）は一言で噛み砕く。\n"
        )
    elif pillar == "contrarian":
        style = (
            "今回は【逆張り】。よくある誤解を1行で否定→なぜ違うかを根拠つきで解説。\n"
            "煽りすぎず、読み終わって“なるほど”と専門性が伝わる長さ（全角150〜300字）。\n"
        )
    else:  # self_type / voice_type / visual = 診断導線
        style = (
            "今回は【声タイプ診断への導線】。声の個性を肯定し、“自分のタイプを知りたい”と"
            "思わせる。簡潔でテンポよく（全角80〜140字）。プロフィールのリンクから無料診断できることを自然に添える。\n"
        )

    return (
        common + style +
        "下敷き（この主旨・情報量・トーンを保ち、より自然で人を惹きつける文に）:\n"
        f"{base}\n"
        "出力はポスト本文のみ。前置き・説明・URL・ハッシュタグの羅列は不要。"
    )


def gemini_twopart_prompt(pillar: str, day_index: int, app_url: str) -> str:
    """2部構成（本投稿フック＋リプ本体）をJSONで生成させる指示。tip / contrarian / artist_analysis で使う。
    本投稿は手順を言い切らず“続きが気になる”状態に。本体は自己返信(リプ)に置く。"""
    base = template_post(pillar, day_index, app_url)
    hook0, body0 = base.get("text", ""), base.get("reply", "") or ""
    extra = ""
    if pillar == "artist_analysis":
        e = ARTIST_ANALYSIS[day_index % len(ARTIST_ANALYSIS)]
        extra = (
            "\n【アーティスト発声解説の鉄則（docs/84）】\n"
            f"- 取り上げる歌手は「{e['artist']}」。この実名を必ずhookに残す。他の歌手名の追加・でっち上げは禁止。\n"
            "- 本人の発声を断定しない。「〜に聞こえます」「音源からの推定」の作法を必ず残す（事実忠実性）。\n"
            "- 貶し・他アーティストとの優劣比較・歌詞の引用は禁止。解説は「なぜ凄いか」の分解に徹する。\n"
            "- bodyの素材末尾にある「8タイプ診断だと【◯◯】系→あなたは？」の診断ブリッジは削らず残す。\n"
        )
    common = (
        "あなたはAIボイストレーナー『ソラ先生』のSNS担当（人間味のある“中の人”）です。"
        "X(旧Twitter)に“2部構成”で投稿します。本投稿で読み手を止めて気にさせ、"
        "具体的な答え（手順・本体）は自分の自己返信(リプ)に置きます。\n"
        "次の2つを作り、**JSONで {\"hook\": \"...\", \"body\": \"...\"} だけ**出力してください"
        "（前後に説明・コードフェンスを付けない）。\n\n"
        "1) hook（本投稿）= 誰の悩みか＋結論の“方向”だけ示し、具体的な手順は書かずに"
        "“続きが気になる”状態で止める。全角90〜150字。\n"
        "   - 末尾に『手順（本体）はリプ（返信）に置いた』と分かる一文を添える（👇可）。\n"
        "   - 読者に『リプして/コメントして』と促すのは禁止。あくまで“自分がリプに続きを書いた”案内。\n"
        "2) body（リプ＝自己返信に置く本体）= 番号付きの具体手順や根拠で、保存したくなる実用度。"
        "全角200〜380字。専門用語は一言で噛み砕く。\n\n"
        "共通: hook・bodyとも**URL/リンクは入れない**。効果は誇張しない（嘘はつかない）。"
        "ハッシュタグはbody末尾に2個まで。絵文字は各1〜3個。\n"
    )
    return (
        common + extra +
        "下敷き（主旨・情報量・トーンを保つ。より自然に人を惹きつける文に）:\n"
        f"hookの素材: {hook0}\n"
        f"bodyの素材:\n{body0}\n"
    )


def gemini_diagnosis_hook_prompt(pillar: str, day_index: int, app_url: str) -> str:
    """診断導線（self_type/voice_type/visual）の“本投稿フックだけ”を生成させる指示。
    早見リプ(cheatsheet_reply)は正本なのでGeminiに触らせず、入口のワクワクだけ磨く。"""
    base = template_post(pillar, day_index, app_url)["text"]
    if pillar == "voice_type":
        n, _, d = VOICE_TYPES[day_index % len(VOICE_TYPES)]
        names = artists_for(n, 3)
        extra = (f"\n今日の主役タイプは【{n}】=「{d}」で、声質が近い例は「{names}」。"
                 f"『{names} みたいな声、憧れる？』のように**この実名を必ず本文に出して**惹きつけ、"
                 "『あなたはどのタイプ？』に繋げる。タイプ名は出してよいが図鑑的な陳列にしない。")
    else:
        # self_type / visual: 全タイプから有名どころを2〜3人、実名で散りばめる。
        marquee = "／".join(artists_for(t, 2) for t in ("rock", "mysterious", "dramatic"))
        extra = (f"\n『{marquee}…あなたは誰系？』のように、**具体的な歌手の実名を必ず2〜3人**本文に出して"
                 "自分ごと化させる（型名だけの占いにしない）。")
    return (
        "あなたはAIボイストレーナー『ソラ先生』のSNS担当（人間味のある“中の人”）です。"
        "X(旧Twitter)の【声タイプ診断】への導線ポストの、**本投稿（フック）だけ**を書きます。\n"
        "鉄則:\n"
        "- 1行目は『あなたの声、歌手なら誰に似てる？』のような“自分の正体を知りたくなる問い”で止める"
        "（好奇心ギャップ＝診断したくなるワクワク）。ラベル陳列・カタログ説明で始めない。\n"
        "- **声質が近い例の歌手を実名で必ず出す**（上記の指定アーティスト。でっち上げ・別の歌手名の追加は禁止）。"
        "実名で“自分ごと”を作りつつ、『あなた自身が誰に一番近いか』は診断結果に取っておく（＝診断へ誘導）。\n"
        "- 『15秒歌うだけ』『8タイプ＋似てる歌手を当てる』『結果はシェアできる』のどれかでベネフィットを一言。\n"
        "- 末尾に『8タイプの早見はリプに置いた』と分かる一文（👇可）。読者にリプを促すのは禁止。\n"
        "- **URL・リンクは絶対に入れない**（誘導はプロフィール固定）。誇張NG。絵文字1〜3個。全角90〜160字。"
        f"{extra}\n\n"
        "下敷き（この主旨・トーンを保ち、より自然で人を惹きつける文に）:\n"
        f"{base}\n"
        "出力は本投稿の本文のみ。前置き・説明・URL・ハッシュタグの羅列は不要。"
    )
